package lab3;

/**
 * Интерфейс, определяющий базовый контракт для любого продаваемого товара в супермаркете.
 * @author Музаев Д.Н.
 * @version 1.0
 */
interface Sellable {
    /**
     * Возвращает актуальную стоимость единицы товара с учетом возможных скидок.
     * @return итоговая цена товара в рублях
     */
    double getPrice();

    /**
     * Формирует подробное текстовое описание товара и его характеристик.
     * @return строка с информацией о товаре
     */
    String getDescription();
}
