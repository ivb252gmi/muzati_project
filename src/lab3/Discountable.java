package lab3;

/**
 * Интерфейс для товаров и сущностей, к которым может быть применена процентная скидка.
 * @author Музаев Д.Н
 * @version 1.0
 */
interface Discountable {
    /**
     * Применяет процентную скидку к товару и возвращает обновленную стоимость.
     * @param percent размер скидки в процентах (от 0 до 100)
     * @return новая цена товара после применения скидки
     */
    double applyDiscount(double percent);
}
